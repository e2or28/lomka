#!/usr/bin/env bash
# Запустить стенд.
#
# Именно так, а не из редактора: редактор Godot держит около гигабайта, и на
# 8 ГБ рядом с Zed это заметно. Редактор нужен, только когда правишь сцены
# мышью; всё остальное — код, терминал и эта команда.
#
# Клавиши в стенде: F1 сверка масштаба, F3 оверлей, F5 перечитать art/,
# Tab добавить слот, R сброс, Esc выход.
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/godot_env.sh"
cd "$PROJECT_DIR"

exec "$GODOT" --path . "$@"
